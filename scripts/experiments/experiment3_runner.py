"""
Experiment 3 — fixed dataset + alignment: compare NED, BLEU, METEOR rankings.

Reuses the OmniDocBench quick_match run from Experiment 1:
  - NED:    sourced from results/experiment1/scores_omnidoc_v15_full.csv (relabelled
            text_edit_acc → NED) for models present there; falls back to parsing
            ``{result_dir}/{model}_quick_match_text_block_per_page_edit.json`` for
            any model not in the E1 CSV (e.g. glm_ocr).
  - BLEU/METEOR: computed via scripts/parse_omnidoc_bleu_meteor.py on matched pairs
            in ``{result_dir}/{model}_quick_match_text_block_result.json``; falls back
            to ``{model}_exp2_quick_match_text_block_result.json`` (same alignment,
            generated by Experiment 2's --result-tag exp2) when the plain file is absent.

All three metrics are grounded in OmniDocBench's quick_match alignment and
normalized text (norm_gt / norm_pred), so the comparison is fair.

Artifacts under results/experiment3/:
  - gt_omnidoc_v15_1355.json
  - scores_metrics.csv          (image, model_name, score, alignment, metric)
  - analysis/                   (omnidoc_ranking_stability output)
  - figures/                    (bump chart, bar chart, Spearman heatmap)
  - manifest.json

Usage:
  python scripts/experiments/experiment3_runner.py

Env:
  RANKSHIFT_ROOT, OMNIDOCBENCH_DIR, GT_JSON   (optional)
  MODELS             — space-separated model subset (default: all in MODELS list)
  METRICS            — subset of NED BLEU METEOR (default: all three)
  SKIP_ANALYSIS=1    — skip stability analysis + figures
  SKIP_NED=1         — skip NED seeding (useful if resuming after NED already done)
"""

from __future__ import annotations

import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

import pandas as pd


def _load_default_models(root: Path) -> list[str]:
    spec = importlib.util.spec_from_file_location(
        "_scoring", root / "scripts" / "run_omnidoc_scoring.py"
    )
    mod = importlib.util.module_from_spec(spec)
    if spec.loader is None:
        raise RuntimeError("Could not load run_omnidoc_scoring.py")
    spec.loader.exec_module(mod)
    return list(mod.MODELS)


def main() -> None:
    root = Path(os.environ.get("RANKSHIFT_ROOT", Path(__file__).resolve().parents[2])).resolve()
    ob = Path(os.environ.get("OMNIDOCBENCH_DIR", root.parent / "OmniDocBench")).resolve()
    gt_default = root / "data" / "omnidocbench" / "OmniDocBench.json"
    gt_src = Path(os.environ.get("GT_JSON", gt_default)).resolve()
    models_env = [x for x in os.environ.get("MODELS", "").split() if x]
    metrics_env = [x for x in os.environ.get("METRICS", "NED BLEU METEOR").split() if x]
    skip_analysis = os.environ.get("SKIP_ANALYSIS", "").lower() in {"1", "true", "yes"}
    skip_ned = os.environ.get("SKIP_NED", "").lower() in {"1", "true", "yes"}

    out_dir = root / "results" / "experiment3"
    out_dir.mkdir(parents=True, exist_ok=True)
    result_dir = Path(
        os.environ.get("EXPERIMENT3_RESULT_DIR", ob / "result")
    ).resolve()
    py = str(root / ".venv" / "bin" / "python") if (root / ".venv").is_dir() else sys.executable

    def run(cmd: list[str]) -> None:
        print("+", " ".join(cmd))
        r = subprocess.run(cmd, cwd=str(root))
        if r.returncode != 0:
            sys.exit(r.returncode)

    # Filter GT to v1.5 (reuse if already there from E1/E2)
    gt_v15 = out_dir / "gt_omnidoc_v15_1355.json"
    if not gt_v15.is_file():
        run([
            py, str(root / "scripts" / "omnidoc_filter_gt_json.py"),
            "--in", str(gt_src),
            "--out", str(gt_v15),
            "--subset", "v1.5",
        ])

    scores_out = out_dir / "scores_metrics.csv"
    model_list = models_env if models_env else _load_default_models(root)

    def _result_save_name(model: str, file_suffix: str) -> str | None:
        """Return the first save_name whose OmniDocBench result file exists, or None."""
        for candidate in (f"{model}_quick_match", f"{model}_exp2_quick_match"):
            if (result_dir / f"{candidate}{file_suffix}").is_file():
                return candidate
        return None

    # --- NED: seed scores_metrics.csv from Experiment 1 CSV, then parse JSON for
    #          any model not covered there (e.g. glm_ocr). ---
    if "NED" in metrics_env and not skip_ned:
        e1_csv = root / "results" / "experiment1" / "scores_omnidoc_v15_full.csv"
        seeded_models: set[str] = set()
        if e1_csv.is_file():
            e1 = pd.read_csv(e1_csv)
            e1_subset = e1[e1["model_name"].isin(model_list)].copy()
            if not e1_subset.empty:
                e1_subset["metric"] = "NED"
                if scores_out.is_file():
                    existing = pd.read_csv(scores_out)
                    # skip models whose NED rows are already present
                    already = set(
                        existing.loc[existing["metric"] == "NED", "model_name"].unique()
                    )
                    e1_subset = e1_subset[~e1_subset["model_name"].isin(already)]
                    if not e1_subset.empty:
                        keep = ~(
                            (existing["metric"] == "NED")
                            & (existing["model_name"].isin(e1_subset["model_name"].unique()))
                        )
                        combined = pd.concat([existing[keep], e1_subset], ignore_index=True)
                        combined.to_csv(scores_out, index=False)
                        seeded_models = set(e1_subset["model_name"].unique())
                        print(f"[NED] seeded {len(seeded_models)} models from E1 CSV → {scores_out.name}")
                    else:
                        seeded_models = already & set(e1["model_name"].unique())
                        print(f"[NED] E1 CSV already applied for {len(seeded_models)} models — skipping")
                else:
                    e1_subset.to_csv(scores_out, index=False)
                    seeded_models = set(e1_subset["model_name"].unique())
                    print(f"[NED] seeded {len(seeded_models)} models from E1 CSV → {scores_out.name}")
        else:
            print(f"[NED] E1 CSV not found ({e1_csv}) — will parse from JSON only")

        # parse JSON for any model not covered by the E1 CSV seed
        for model in model_list:
            if model in seeded_models:
                continue
            save_name = _result_save_name(model, "_text_block_per_page_edit.json")
            if save_name is None:
                print(f"[NED] skip {model} — no quick_match per_page_edit.json found")
                continue
            run([
                py, str(root / "scripts" / "parse_omnidoc_results.py"),
                "--result-dir", str(result_dir),
                "--model", model,
                "--save-name", save_name,
                "--out", str(scores_out),
                "--alignment-label", "quick_match",
                "--metric-name", "NED",
            ])

    # --- BLEU / METEOR: compute from matched pairs in text_block_result.json ---
    bleu_meteor = [m for m in metrics_env if m in ("BLEU", "METEOR")]
    if bleu_meteor:
        for model in model_list:
            # skip models whose rows for all requested metrics already exist
            if scores_out.is_file():
                existing = pd.read_csv(scores_out)
                done = set(existing.loc[existing["model_name"] == model, "metric"].unique())
                remaining = [m for m in bleu_meteor if m not in done]
                if not remaining:
                    print(f"[BLEU/METEOR] skip {model} — already in scores_metrics.csv")
                    continue
            else:
                remaining = bleu_meteor

            save_name = _result_save_name(model, "_text_block_result.json")
            if save_name is None:
                print(f"[BLEU/METEOR] skip {model} — no quick_match text_block_result.json found")
                continue
            run([
                py, str(root / "scripts" / "parse_omnidoc_bleu_meteor.py"),
                "--result-dir", str(result_dir),
                "--save-name", save_name,
                "--model", model,
                "--out", str(scores_out),
                "--alignment", "quick_match",
                "--metrics", *remaining,
            ])

    if not scores_out.is_file():
        print("No scores written — check that Experiment 1 result files exist in OmniDocBench/result/")
        return

    n_models = pd.read_csv(scores_out)["model_name"].nunique()
    print(f"\nscores_metrics.csv: {len(pd.read_csv(scores_out))} rows, {n_models} models")

    if not skip_analysis:
        analysis_dir = out_dir / "analysis"
        run([
            py, str(root / "scripts" / "omnidoc_ranking_stability.py"),
            "--gt-json", str(gt_v15),
            "--scores-csv", str(scores_out),
            "--out-dir", str(analysis_dir),
            "--plot",
        ])
        run([
            py, str(root / "scripts" / "experiments" / "experiment3_figures.py"),
            "--experiment-dir", str(out_dir),
        ])

    manifest = {
        "experiment": 3,
        "dataset": "omnidocbench v1.5 (1355 pages)",
        "alignment": "quick_match (reused from Experiment 1 — no re-scoring)",
        "metrics": metrics_env,
        "scores": str(scores_out),
        "analysis_dir": str(out_dir / "analysis"),
        "figures_dir": str(out_dir / "figures"),
        "notes": [
            "NED seeded from results/experiment1/scores_omnidoc_v15_full.csv (text_edit_acc relabelled NED); "
            "models absent from E1 CSV parsed from {model}_quick_match_text_block_per_page_edit.json.",
            "BLEU/METEOR from {model}_quick_match_text_block_result.json (falls back to "
            "{model}_exp2_quick_match_text_block_result.json — same alignment).",
            "All three metrics use the same quick_match alignment and OmniDocBench normalization.",
        ],
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"Wrote {out_dir / 'manifest.json'}")


if __name__ == "__main__":
    main()
